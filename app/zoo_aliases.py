"""動物園の愛称・別名（検索用）。

正式名称で登録しているため、愛称で検索すると見つからない問題への対応。
例: 「のんほいパーク」→ 豊橋総合動植物公園

ここに書いた文字列は
  - 一覧の検索・サジェストの対象になる
  - 詳細ページの説明文と meta description に入る（検索エンジン向け）

書くときのルール（zoo_features.py と同じ考え方）:
- 裏が取れた愛称だけを書く。推測で書かない
- 公式サイトのドメインや公式表記に現れるものを優先する
  （例: nonhoi.jp / africansafari.co.jp / morikirara.jp）
- 正式名称の一部になっている語は不要。
  「愛媛県立とべ動物園」は「とべ動物園」で既にヒットするので書かない
- 表記ゆれ（カタカナ/ひらがな/英字）は並べて書いてよい

キーは zoos テーブルの name と完全一致させること。
"""

# 園名 -> 愛称・別名のリスト
ALIASES: dict[str, list[str]] = {
    # 公式サイト nonhoi.jp
    "豊橋総合動植物公園": ["のんほいパーク", "のんほいぱーく", "ノンホイパーク"],

    # 正式名称は「よこはま動物園ズーラシア」。登録名に「ズーラシア」が無い
    "横浜市立よこはま動物園": ["ズーラシア", "よこはま動物園ズーラシア"],

    # 公式サイト fujisafari.co.jp
    "富士自然動物公園": ["富士サファリパーク", "富士サファリ"],

    # 公式サイト africansafari.co.jp
    "九州自然動物公園": ["アフリカンサファリ", "九州自然動物公園アフリカンサファリ"],

    # 公式サイト safariland.jp
    "秋吉台自然動物公園": ["秋吉台サファリランド", "サファリランド"],

    # 公式サイト morikirara.jp
    "西海国立公園九十九島動植物園": ["森きらら", "九十九島動植物園"],

    # 2023年リニューアル後の愛称。公式サイト zoomo.co.jp
    "盛岡市動物公園": ["ZOOMO", "ズーモ", "盛岡市動物公園ZOOMO"],
}


def get_aliases(name: str) -> list[str]:
    """園名に対応する愛称のリストを返す。未登録なら空リスト。"""
    if not name:
        return []
    return ALIASES.get(name.strip(), [])
