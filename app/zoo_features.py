"""各動物園の特徴（詳細ページの紹介文で使う）。

水族館側（aquarium_features.py）と同じ運用にする。
自動収集は精度が出ないため、ここは**手で書いて管理する**。

書くときのルール:
- 調べて裏が取れた事実だけを書く。あいまいなものは書かない
- 「日本一」「世界初」「唯一」の類は、必ず出典を確認してから書く。
  こうした記録は入れ替わるので、怪しくなったら消す
- 文章は他所からの引用ではなく、自分の言葉で短く書く
- 1〜2文。長い説明は公式サイトに任せる

キーは zoos テーブルの name と完全一致させること。

※ 中身は未着手。空のままでも詳細ページは正しく動く
   （紹介文の段落が1つ減るだけ）。埋めた分だけページが厚くなる。
"""

# 園名 -> 紹介文に差し込む1〜2文
FEATURES: dict[str, str] = {
    # 例（実際に裏を取ってから有効化すること）:
    # "旭川市旭山動物園":
    #     "動物本来の行動を見せる「行動展示」で知られています。"
    #     "アザラシが円柱水槽を垂直に泳ぐ「マリンウェイ」が代表的な展示です。",
}


def get_feature(name: str) -> str:
    """園名に対応する紹介文を返す。未登録なら空文字。"""
    if not name:
        return ""
    return FEATURES.get(name.strip(), "")
